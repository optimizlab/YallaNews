  String translate(String key) {
    final localeMap = _localizedStrings[locale.languageCode];
    if (localeMap != null && localeMap.containsKey(key)) {
      return localeMap[key]!;
    }
    final ar = _localizedStrings['ar']?[key];
    if (ar != null) return ar;
    return _localizedStrings['en']?[key] ?? key;
  }
